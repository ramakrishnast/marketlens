import { useState } from 'react'
import { api } from '../../api'
import { AIBadge, AsOf, Card, ErrorBox, Loading, Markdown, NeedsKey, Segmented, fmt, useApi } from '../ui'

const ITEM_NAMES = {
  '1.01': 'Material agreement', '2.02': 'Results of operations (earnings)', '2.03': 'Financial obligation',
  '5.02': 'Officer/director change', '5.07': 'Shareholder vote', '7.01': 'Reg FD disclosure', '8.01': 'Other events',
  '9.01': 'Financial statements/exhibits', '2.01': 'Acquisition/disposition', '1.02': 'Termination of agreement',
}

function Summary({ ticker, filings }) {
  const latest = filings.find((f) => f.form === '10-Q' || f.form === '10-K')
  const cached = useApi(latest ? `/ticker/${encodeURIComponent(ticker)}/filings/summary?accession=${latest.accession}` : null)
  const [res, setRes] = useState(null)
  const [busy, setBusy] = useState(false)
  if (!latest) return null
  const data = res || cached.data
  const run = async (force = false) => {
    setBusy(true)
    try { setRes(await api.post(`/ticker/${encodeURIComponent(ticker)}/filings/summary`, { accession: latest.accession, force })) } catch (e) { setRes({ error: e.message }) }
    setBusy(false)
  }
  return (
    <Card title={`AI summary of the latest ${latest.form} (filed ${fmt.date(latest.filing_date)})`}
      right={data?.summary ? <div className="flex items-center gap-2"><AIBadge /><button className="btn text-xs" disabled={busy} onClick={() => run(true)}>Regenerate</button></div> : null}>
      {cached.loading && <Loading />}
      {data?.needs_key && <NeedsKey what="Filing summaries" />}
      {data?.error && <ErrorBox error={data.error} />}
      {data && !data.summary && !data.needs_key && !data.error && (
        data.ai_enabled === false ? <NeedsKey what="Filing summaries" /> :
        <button className="btn btn-primary" disabled={busy} onClick={() => run(false)}>{busy ? 'Reading the filing… (≈30s)' : `Summarize ${latest.form} with AI`}</button>
      )}
      {busy && data?.summary && <Loading text="Regenerating…" />}
      {data?.summary && <>
        <Markdown text={data.summary} />
        <p className="text-xs text-muted mt-3 border-t border-line pt-2">
          AI-generated by {data.model} from the filing text on {fmt.datetime(data.created_at)}. It can be wrong: verify in the{' '}
          <a className="underline" href={latest.url} target="_blank" rel="noreferrer">original {latest.form}</a>.
        </p>
      </>}
    </Card>
  )
}

export default function Filings({ ticker }) {
  const { data, error, loading, reload } = useApi(`/ticker/${encodeURIComponent(ticker)}/filings`)
  const [form, setForm] = useState('all')
  if (loading) return <Loading text="Loading SEC filings…" />
  if (error) return <ErrorBox error={error} onRetry={reload} />
  if (!data.available) return <Card><div className="text-sm text-muted">{data.reason}</div></Card>
  const rows = data.filings.filter((f) => form === 'all' || f.form === form)
  return (
    <div className="grid xl:grid-cols-2 gap-4 items-start">
      <Card title="Recent SEC filings" right={<div className="flex items-center gap-3"><AsOf asOf={{ ...data.as_of }} label="Fetched" /><Segmented options={['all', '10-K', '10-Q', '8-K']} value={form} onChange={setForm} /></div>}>
        <div className="divide-y divide-line">
          {rows.map((f) => (
            <a key={f.accession} href={f.url} target="_blank" rel="noreferrer" className="flex gap-3 py-2 text-sm hover:bg-panel2 -mx-2 px-2 rounded">
              <span className="font-mono text-xs text-muted w-20 shrink-0 pt-0.5">{f.filing_date}</span>
              <span className={`font-mono text-xs w-12 shrink-0 pt-0.5 ${f.form === '8-K' ? 'text-warn' : 'text-accent'}`}>{f.form}</span>
              <span className="flex-1 min-w-0">
                {f.form === '8-K' ? (f.items ? f.items.split(',').map((i) => ITEM_NAMES[i.trim()] || `Item ${i}`).join(' · ') : '8-K') : `${f.form === '10-K' ? 'Annual' : 'Quarterly'} report${f.report_date ? ` for period ending ${fmt.date(f.report_date)}` : ''}`}
              </span>
              <span className="text-muted">↗</span>
            </a>
          ))}
        </div>
      </Card>
      <Summary ticker={ticker} filings={data.filings} />
    </div>
  )
}
