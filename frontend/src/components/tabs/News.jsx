import { useState } from 'react'
import { Bar, CartesianGrid, ComposedChart, Line, ReferenceDot, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts'
import { api } from '../../api'
import { AIBadge, AsOf, Card, ErrorBox, Loading, Markdown, NeedsKey, Segmented, fmt, useApi } from '../ui'

const axis = { stroke: 'var(--muted)', fontSize: 11, tickLine: false, axisLine: false }

export function SentimentChip({ s, label }) {
  if (s === null || s === undefined) return <span className="text-xs text-muted">—</span>
  const cls = s > 0.15 ? 'text-up border-up/40' : s < -0.15 ? 'text-down border-down/40' : 'text-muted border-line'
  return <span className={`num text-[11px] border rounded px-1.5 py-0.5 ${cls}`} title={label}>{s > 0 ? '+' : ''}{s.toFixed(2)}</span>
}

function TrendChart({ ticker }) {
  const [days, setDays] = useState('30')
  const { data, error, loading } = useApi(`/ticker/${encodeURIComponent(ticker)}/sentiment?days=${days}`)
  return (
    <Card title="Sentiment trend vs price" subtitle="Bars: daily mean headline sentiment (−1 to +1). Line: closing price. Dots: sentiment spikes vs the ticker's 30-day baseline."
      right={<Segmented options={[{ value: '7', label: '7D' }, { value: '30', label: '30D' }, { value: '90', label: '90D' }]} value={days} onChange={setDays} />}>
      {loading && <Loading />}
      {error && <ErrorBox error={error} />}
      {data && <>
        <ResponsiveContainer width="100%" height={260}>
          <ComposedChart data={data.points} margin={{ left: -10, right: 0, top: 8 }}>
            <CartesianGrid stroke="var(--line)" strokeDasharray="3 3" vertical={false} />
            <XAxis dataKey="date" {...axis} tickFormatter={(d) => d.slice(5)} minTickGap={24} />
            <YAxis yAxisId="s" {...axis} domain={[-1, 1]} width={40} />
            <YAxis yAxisId="p" orientation="right" {...axis} domain={['auto', 'auto']} width={50} />
            <Tooltip contentStyle={{ background: 'var(--panel)', border: '1px solid var(--line)', borderRadius: 8, fontSize: 12 }}
              formatter={(v, n) => [v === null ? '—' : n === 'Close' ? fmt.num(v) : Number(v).toFixed(2), n]} />
            <Bar yAxisId="s" dataKey="sentiment" name="Sentiment" fill="var(--accent)" opacity={0.7} />
            <Line yAxisId="s" dataKey="sent_7d" name="7-day avg" stroke="#f59e0b" dot={false} strokeWidth={1.5} connectNulls />
            <Line yAxisId="p" dataKey="close" name="Close" stroke="#60a5fa" dot={false} strokeWidth={2} connectNulls />
            {data.spikes.map((s) => <ReferenceDot key={s.date} yAxisId="s" x={s.date} y={s.sentiment} r={5} fill={s.direction === 'positive' ? 'var(--up)' : 'var(--down)'} stroke="var(--panel)" />)}
          </ComposedChart>
        </ResponsiveContainer>
        {data.coverage_note && <p className="text-xs text-warn mt-1">{data.coverage_note}</p>}
        {data.spikes.length > 0 && (
          <div className="mt-2 text-sm space-y-1">
            <div className="label">Sentiment spikes</div>
            {data.spikes.map((s) => <div key={s.date}><span className="font-mono text-xs text-muted mr-2">{s.date}</span>{s.direction} shift: {s.sentiment.toFixed(2)} vs baseline {s.baseline.toFixed(2)} (z = {s.z}, {s.headlines} headlines)</div>)}
          </div>
        )}
      </>}
    </Card>
  )
}

function Narrative({ ticker }) {
  const cached = useApi(`/ticker/${encodeURIComponent(ticker)}/news/summary`)
  const [res, setRes] = useState(null)
  const [busy, setBusy] = useState(false)
  const data = res || cached.data
  const run = async (force) => {
    setBusy(true)
    try { setRes(await api.post(`/ticker/${encodeURIComponent(ticker)}/news/summary`, { force })) } catch (e) { setRes({ error: e.message }) }
    setBusy(false)
  }
  const refs = data?.refs || []
  const linked = data?.summary?.replace(/\[(\d+)\]/g, (m, n) => { const r = refs[Number(n) - 1]; return r ? `[[${n}]](${r.url})` : m })
  return (
    <Card title="AI summary of the narrative" right={data?.summary ? <div className="flex gap-2 items-center"><AIBadge /><button className="btn text-xs" onClick={() => run(true)} disabled={busy}>Regenerate</button></div> : null}>
      {cached.loading && <Loading />}
      {(data?.needs_key || data?.ai_enabled === false) && <NeedsKey what="News summaries" />}
      {data?.error && <ErrorBox error={data.error} />}
      {data && !data.summary && data.ai_enabled && <button className="btn btn-primary" onClick={() => run(false)} disabled={busy}>{busy ? 'Summarizing…' : 'Summarize recent headlines'}</button>}
      {data?.summary && <>
        <Markdown text={linked} />
        <p className="text-xs text-muted mt-3 border-t border-line pt-2">AI-generated by {data.model} from the {refs.length} headlines listed below; [n] links go to the original articles.</p>
      </>}
    </Card>
  )
}

export default function News({ ticker }) {
  const { data, error, loading, reload } = useApi(`/ticker/${encodeURIComponent(ticker)}/news?days=30`)
  const refresh = async () => { await api.post(`/ticker/${encodeURIComponent(ticker)}/news/refresh`); reload() }
  return (
    <div className="grid xl:grid-cols-2 gap-4 items-start">
      <div className="space-y-4">
        <TrendChart ticker={ticker} />
        <Narrative ticker={ticker} />
      </div>
      <Card title="Recent headlines" subtitle={data ? `Sentiment scored locally with ${data.scorer === 'finbert' ? 'FinBERT' : 'the finance lexicon (install FinBERT with make finbert)'}. Headlines and short snippets only; click through to read.` : ''}
        right={<div className="flex items-center gap-2">{data && <AsOf asOf={data.as_of} label="Fetched" />}<button className="btn text-xs" onClick={refresh}>↻</button></div>}>
        {loading && <Loading />}
        {error && <ErrorBox error={error} onRetry={reload} />}
        {data && data.items.length === 0 && <div className="text-sm text-muted">No headlines found.</div>}
        <div className="divide-y divide-line max-h-[900px] overflow-auto -mx-2">
          {data?.items.map((n) => (
            <a key={n.id} href={n.url} target="_blank" rel="noreferrer" className="flex gap-3 px-2 py-2.5 hover:bg-panel2">
              <div className="pt-0.5"><SentimentChip s={n.sentiment} label={n.sentiment_label} /></div>
              <div className="min-w-0 flex-1">
                <div className="text-sm leading-snug">{n.headline}</div>
                {n.snippet && <div className="text-xs text-muted mt-0.5 line-clamp-2">{n.snippet}</div>}
                <div className="text-[11px] text-muted mt-1 font-mono">{n.source} · {fmt.datetime(n.published_at)}</div>
              </div>
            </a>
          ))}
        </div>
      </Card>
    </div>
  )
}
